const fs = require('node:fs');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const root = path.resolve(__dirname, '..');
const anatomy = path.join(root, 'anatomy-source');
const command = process.platform==='win32' ? 'cmd.exe' : 'npm';
const args = process.platform==='win32' ? ['/d','/s','/c','npm run build -- --base=./'] : ['run','build','--','--base=./'];
const result = spawnSync(command, args, {cwd:anatomy, stdio:'inherit', windowsHide:true});
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status || 1);
const built = path.join(anatomy, 'dist');
const destination = path.join(root, 'content', 'anatomy');
if (!fs.existsSync(path.join(built, 'models', 'skeletal.glb'))) throw Error('Build does not contain the bundled anatomy models.');
if (fs.realpathSync(path.dirname(destination)) !== path.join(fs.realpathSync(root), 'content')) throw Error('Unexpected output directory.');
fs.rmSync(destination, {recursive:true, force:true});
fs.cpSync(built, destination, {recursive:true});
const index = path.join(destination, 'index.html');
fs.writeFileSync(index,fs.readFileSync(index,'utf8').replace('</head>','  <script defer src="../assets/file-entry.js"></script>\n</head>'));
console.log('Updated content/anatomy from the verified atlas build.');
require('./update-release-marker.cjs')();
